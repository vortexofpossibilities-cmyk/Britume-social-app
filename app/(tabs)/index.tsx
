import React, { useCallback, useMemo, useState } from 'react';
import {
  ActivityIndicator,
  Alert,
  FlatList,
  Pressable,
  RefreshControl,
  Share,
  StyleSheet,
  Text,
  TextInput,
  View,
} from 'react-native';
import { Ionicons } from '@expo/vector-icons';
import { router, useFocusEffect } from 'expo-router';
import {
  fetchPublicPosts,
  type FeedPost,
} from '../../src/lib/posts';
import { theme } from '../../src/lib/theme';

const BLUE = '#168BFF';

export default function HomeScreen() {
  const [posts, setPosts] = useState<FeedPost[]>([]);
  const [search, setSearch] = useState('');
  const [loading, setLoading] = useState(true);
  const [refreshing, setRefreshing] = useState(false);
  const [error, setError] = useState('');
  const [likedPosts, setLikedPosts] = useState<string[]>([]);
  const [savedPosts, setSavedPosts] = useState<string[]>([]);

  const loadPosts = useCallback(async (refresh = false) => {
    if (refresh) {
      setRefreshing(true);
    } else {
      setLoading(true);
    }

    setError('');

    try {
      const freshPosts = await fetchPublicPosts();
      setPosts(freshPosts);
    } catch (e) {
      setError(
        e instanceof Error ? e.message : 'Could not load posts.',
      );
    } finally {
      setLoading(false);
      setRefreshing(false);
    }
  }, []);

  useFocusEffect(
    useCallback(() => {
      void loadPosts();
    }, [loadPosts]),
  );

  const filteredPosts = useMemo(() => {
    const q = search.trim().toLowerCase();

    if (!q) return posts;

    return posts.filter((post) =>
      (post.content ?? '').toLowerCase().includes(q),
    );
  }, [posts, search]);

  const toggleLike = (id: string) => {
    setLikedPosts((current) =>
      current.includes(id)
        ? current.filter((item) => item !== id)
        : [...current, id],
    );
  };

  const toggleSave = (id: string) => {
    setSavedPosts((current) =>
      current.includes(id)
        ? current.filter((item) => item !== id)
        : [...current, id],
    );
  };

  const sharePost = async (content: string) => {
    try {
      await Share.share({ message: content });
    } catch {
      Alert.alert('Sharing unavailable', 'Please try again.');
    }
  };

  const Header = (
    <View>
      <View style={styles.topBar}>
        <View style={styles.brandMark}>
          <Text style={styles.brandLetter}>B</Text>
        </View>

        <View style={styles.brandText}>
          <Text style={styles.brandName}>BRITUME</Text>
          <Text style={styles.tagline}>Vortex of Possibilities</Text>
          <Text style={styles.byline}>by brilliant mere</Text>
        </View>

        <Pressable
          accessibilityRole="button"
          accessibilityLabel="Notifications"
          style={styles.topButton}
          onPress={() => router.push('/notifications')}
        >
          <Ionicons
            name="notifications-outline"
            size={25}
            color={theme.text}
          />
        </Pressable>

        <Pressable
          accessibilityRole="button"
          accessibilityLabel="Open BRITUME AI"
          style={styles.topButton}
          onPress={() => router.push('/ai')}
        >
          <Text style={styles.aiIcon}>✨</Text>
        </Pressable>

        <Pressable
          accessibilityRole="button"
          accessibilityLabel="Create"
          style={styles.topButton}
          onPress={() => router.push('/(tabs)/create')}
        >
          <Ionicons name="add-circle" size={27} color={BLUE} />
        </Pressable>
      </View>

      <View style={styles.searchBox}>
        <Ionicons
          name="search-outline"
          size={21}
          color={theme.muted}
        />

        <TextInput
          value={search}
          onChangeText={setSearch}
          placeholder="Search people, posts and communities..."
          placeholderTextColor={theme.muted}
          style={styles.searchInput}
          returnKeyType="search"
          clearButtonMode="while-editing"
        />

        <Pressable
          accessibilityRole="button"
          accessibilityLabel="Open Discover"
          onPress={() => router.push('/(tabs)/discover')}
        >
          <Ionicons
            name="options-outline"
            size={21}
            color={theme.muted}
          />
        </Pressable>
      </View>

      <View style={styles.sectionHeading}>
        <Text style={styles.sectionTitle}>Stories</Text>

        <Pressable
          accessibilityRole="button"
          accessibilityLabel="Add a story"
          style={styles.addButton}
          onPress={() => router.push('/stories')}
        >
          <Ionicons name="add-circle" size={25} color={BLUE} />
        </Pressable>
      </View>

      <View style={styles.storyRow}>
        <Pressable
          style={styles.storyItem}
          onPress={() => router.push('/stories')}
        >
          <View style={[styles.storyCircle, styles.myStory]}>
            <Ionicons name="add" size={29} color="#FFFFFF" />
          </View>
          <Text style={styles.storyLabel}>Add story</Text>
        </Pressable>

        <View style={styles.storyEmpty}>
          <Ionicons
            name="people-outline"
            size={25}
            color={theme.muted}
          />
          <Text style={styles.storyEmptyText}>
            Stories from people you follow appear here.
          </Text>
        </View>
      </View>

      <View style={styles.sectionHeading}>
        <Text style={styles.sectionTitle}>Posts</Text>

        <Pressable
          accessibilityRole="button"
          accessibilityLabel="Create a post"
          style={styles.addButton}
          onPress={() => router.push('/(tabs)/create')}
        >
          <Ionicons name="add-circle" size={25} color={BLUE} />
        </Pressable>
      </View>

      {error ? (
        <View style={styles.errorBox}>
          <Text style={styles.errorText}>{error}</Text>
          <Pressable onPress={() => void loadPosts()}>
            <Text style={styles.retryText}>Try again</Text>
          </Pressable>
        </View>
      ) : null}
    </View>
  );

  const VideoSection = (
    <View style={styles.videoSection}>
      <View style={styles.sectionHeading}>
        <Text style={styles.sectionTitle}>Videos</Text>

        <Pressable
          accessibilityRole="button"
          accessibilityLabel="Add a video"
          style={styles.addButton}
          onPress={() => router.push('/(tabs)/create')}
        >
          <Ionicons name="add-circle" size={25} color={BLUE} />
        </Pressable>
      </View>

      <Pressable
        style={styles.videoCard}
        onPress={() => router.push('/stories')}
      >
        <View style={styles.videoArtwork}>
          <Ionicons name="play-circle" size={58} color={BLUE} />
        </View>

        <View style={styles.videoBottom}>
          <Text style={styles.videoCaption}>
            Explore moments on BRITUME
          </Text>
          <Ionicons
            name="chevron-forward"
            size={22}
            color={BLUE}
          />
        </View>
      </Pressable>
    </View>
  );

  if (loading) {
    return (
      <View style={styles.loading}>
        <ActivityIndicator size="large" color={BLUE} />
      </View>
    );
  }

  return (
    <FlatList
      style={styles.screen}
      contentContainerStyle={styles.content}
      data={filteredPosts}
      keyExtractor={(item) => item.id}
      numColumns={2}
      columnWrapperStyle={styles.postRow}
      ListHeaderComponent={Header}
      ListFooterComponent={VideoSection}
      refreshControl={
        <RefreshControl
          refreshing={refreshing}
          onRefresh={() => void loadPosts(true)}
          tintColor={BLUE}
        />
      }
      ListEmptyComponent={
        <View style={styles.emptyBox}>
          <Ionicons
            name="chatbubbles-outline"
            size={36}
            color={BLUE}
          />

          <Text style={styles.emptyTitle}>
            {search.trim() ? 'No matching posts' : 'Welcome to BRITUME'}
          </Text>

          <Text style={styles.emptyText}>
            {search.trim()
              ? 'Try searching for something else.'
              : 'Create a post to start sharing with the community.'}
          </Text>

          {!search.trim() && (
            <Pressable
              style={styles.primaryButton}
              onPress={() => router.push('/(tabs)/create')}
            >
              <Ionicons name="add" size={20} color="#FFFFFF" />
            </Pressable>
          )}
        </View>
      }
      renderItem={({ item }) => (
        <View style={styles.postCard}>
          <View style={styles.postHeader}>
            <View style={styles.avatar}>
              <Ionicons name="person" size={20} color={BLUE} />
            </View>

            <View style={styles.postAuthor}>
              <Text style={styles.authorName}>BRITUME member</Text>
              <Text style={styles.postDate}>
                {new Date(item.created_at).toLocaleDateString()}
              </Text>
            </View>

            <Pressable
              accessibilityRole="button"
              accessibilityLabel="More post options"
              onPress={() =>
                Alert.alert('Post options', 'Choose an action.', [
                  {
                    text: 'Share',
                    onPress: () => void sharePost(item.content ?? ''),
                  },
                  { text: 'Cancel', style: 'cancel' },
                ])
              }
            >
              <Ionicons
                name="ellipsis-vertical"
                size={19}
                color={theme.muted}
              />
            </Pressable>
          </View>

          <Text style={styles.postContent} numberOfLines={8}>
            {item.content}
          </Text>

          <View style={styles.postActions}>
            <Pressable
              accessibilityRole="button"
              accessibilityLabel="Like post"
              onPress={() => toggleLike(item.id)}
            >
              <Ionicons
                name={
                  likedPosts.includes(item.id)
                    ? 'heart'
                    : 'heart-outline'
                }
                size={21}
                color={
                  likedPosts.includes(item.id)
                    ? '#E84C75'
                    : theme.muted
                }
              />
            </Pressable>

            <Pressable
              accessibilityRole="button"
              accessibilityLabel="Comment on post"
              onPress={() =>
                Alert.alert(
                  'Comments',
                  'Commenting is connected to the Supabase comments table.',
                )
              }
            >
              <Ionicons
                name="chatbubble-outline"
                size={21}
                color={theme.muted}
              />
            </Pressable>

            <Pressable
              accessibilityRole="button"
              accessibilityLabel="Share post"
              onPress={() => void sharePost(item.content ?? '')}
            >
              <Ionicons
                name="share-social-outline"
                size={21}
                color={theme.muted}
              />
            </Pressable>

            <Pressable
              accessibilityRole="button"
              accessibilityLabel="Save post"
              onPress={() => toggleSave(item.id)}
            >
              <Ionicons
                name={
                  savedPosts.includes(item.id)
                    ? 'bookmark'
                    : 'bookmark-outline'
                }
                size={21}
                color={
                  savedPosts.includes(item.id) ? BLUE : theme.muted
                }
              />
            </Pressable>

            <Pressable
              accessibilityRole="button"
              accessibilityLabel="Download post"
              onPress={() =>
                Alert.alert(
                  'Download',
                  'Downloading media is a coming soon feature.',
                )
              }
            >
              <Ionicons
                name="download-outline"
                size={21}
                color={theme.muted}
              />
            </Pressable>
          </View>
        </View>
      )}
    />
  );
}

